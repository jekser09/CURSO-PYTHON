
#? Operadores aritmeticos

#? Suma
a,b = 10,3
suma = a + b
print(f'{a} + {b} = {suma}')
#? Resta
a,b = 10,3
resta = a - b
print(f'{a} - {b} = {resta}')
#? Multiplicacion
a,b = 10,3
multiplicacion = a * b
print(f'{a} * {b} = {multiplicacion}')
#? Division
a,b = 10,3
division = a/b
print(f'{a} / {b} = {division}')
#? Division entera (Devuelve solo la parte entera del resultado)
a,b = 10,3
division_entera = a//b
print(f'{a} // {b} = {division_entera}')
#? Division modulo (Devuelve el residuo de la divsion)
a,b = 10,3
division_modulo = a%b
print(f'{a} % {b} = {division_modulo}')
#? Exponente (potencia)
a,b = 10,3
potencia = a**b
print(f'{a}^{b} = {potencia}')
